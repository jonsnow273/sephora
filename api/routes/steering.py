# Activation Steering REST API routes
# GET  /api/steering/presets               - Get all available presets
# POST /api/steering/preset/{name}         - Apply a preset
# GET  /api/steering/directions            - Get current steering directions
# POST /api/steering/direction             - Add or update a direction
# DELETE /api/steering/direction/{id}      - Remove a direction
# GET  /api/steering/activations           - Get live layer activations
# POST /api/steering/reset                 - Reset to neutral
